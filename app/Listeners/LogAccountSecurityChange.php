<?php

namespace App\Listeners;

use App\Models\User;
use Illuminate\Auth\Events\PasswordReset;
use Laravel\Fortify\Events\PasswordUpdatedViaController;
use Laravel\Fortify\Events\RecoveryCodesGenerated;
use Laravel\Fortify\Events\TwoFactorAuthenticationConfirmed;
use Laravel\Fortify\Events\TwoFactorAuthenticationDisabled;
use Laravel\Fortify\Events\TwoFactorAuthenticationEnabled;
use Laravel\Passkeys\Events\PasskeyDeleted;
use Laravel\Passkeys\Events\PasskeyRegistered;

/**
 * Keep an audit-trail entry for every change to how an account is signed in
 * to: its password, its second factor, its passkeys. A stolen session's first
 * move is usually one of these, and the owner is the one to ask about it.
 *
 * Filed under the account and caused by its owner — these are only ever done
 * by the account holder themselves, a password reset included: whoever holds
 * the e-mailed link is, as far as the application can tell, its owner.
 */
class LogAccountSecurityChange
{
    public function handlePasswordUpdated(PasswordUpdatedViaController $event): void
    {
        $this->log($event->user, 'password_changed', 'Password changed by %s');
    }

    public function handlePasswordReset(PasswordReset $event): void
    {
        $this->log($event->user, 'password_reset', 'Password reset by %s through an e-mailed link');
    }

    public function handleTwoFactorEnabled(TwoFactorAuthenticationEnabled $event): void
    {
        $this->log($event->user, 'two_factor_enabled', 'Two-factor authentication turned on by %s');
    }

    public function handleTwoFactorConfirmed(TwoFactorAuthenticationConfirmed $event): void
    {
        $this->log($event->user, 'two_factor_confirmed', 'Two-factor authentication confirmed by %s');
    }

    public function handleTwoFactorDisabled(TwoFactorAuthenticationDisabled $event): void
    {
        $this->log($event->user, 'two_factor_disabled', 'Two-factor authentication turned off by %s');
    }

    public function handleRecoveryCodesGenerated(RecoveryCodesGenerated $event): void
    {
        $this->log($event->user, 'recovery_codes_regenerated', 'Two-factor recovery codes regenerated by %s');
    }

    public function handlePasskeyRegistered(PasskeyRegistered $event): void
    {
        $this->log($event->user, 'passkey_added', 'Passkey added by %s', ['passkey_id' => $event->passkey->getKey()]);
    }

    public function handlePasskeyDeleted(PasskeyDeleted $event): void
    {
        $this->log($event->user, 'passkey_removed', 'Passkey removed by %s', ['passkey_id' => $event->passkey->getKey()]);
    }

    /**
     * @param  string  $description  a sentence with one `%s` for the account holder's name
     * @param  array<string, mixed>  $properties
     */
    private function log(mixed $user, string $event, string $description, array $properties = []): void
    {
        // Every account here is a User; the events are typed for any guard.
        if (! $user instanceof User) {
            return;
        }

        activity()
            ->performedOn($user)
            ->causedBy($user)
            ->event($event)
            ->withProperties($properties)
            ->log(sprintf($description, $user->name));
    }
}
